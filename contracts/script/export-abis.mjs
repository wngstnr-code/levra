import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const targetDir = join(root, "..", "packages", "shared", "abis");

const artifacts = [
  { contract: "IMarginRouter", name: "marginRouterAbi", file: "marginRouter" },
  { contract: "IRiskManager", name: "riskManagerAbi", file: "riskManager" },
  { contract: "ISessionOracle", name: "sessionOracleAbi", file: "sessionOracle" },
  { contract: "ILens", name: "lensAbi", file: "lens" },
  { contract: "ILiquidator", name: "liquidatorAbi", file: "liquidator" },
  { contract: "IAnchoredStockOracle", name: "anchoredStockOracleAbi", file: "anchoredStockOracle" },
  { contract: "IMorpho", name: "morphoAbi", file: "morpho" },
  { contract: "IMetaMorpho", name: "metaMorphoAbi", file: "metaMorpho" },
  { contract: "IERC20Permit", name: "erc20PermitAbi", file: "erc20Permit" },
];

const header = "// Generated by contracts/script/export-abis.mjs. Do not edit by hand.\n";

mkdirSync(targetDir, { recursive: true });

const abiOf = (contract) => JSON.parse(readFileSync(join(outDir, `${contract}.sol`, `${contract}.json`), "utf8")).abi;

// Morpho keeps its events in a library, so they are added to the interface ABI here.
const extraEvents = { IMorpho: "EventsLib" };

// Public reads that the contract has and its interface does not: roles and ownership.
const extraViews = {
  IMarginRouter: { from: "MarginRouter", names: ["isKeeper", "feeRecipient", "owner", "pendingOwner"] },
  IRiskManager: { from: "RiskManager", names: ["calendarPoster", "guardian", "owner", "pendingOwner"] },
  ILiquidator: { from: "Liquidator", names: ["owner", "pendingOwner"] },
};

function viewsOf(contract) {
  const extra = extraViews[contract];
  if (!extra) return [];
  const abi = abiOf(extra.from);
  return extra.names.map((name) => {
    const item = abi.find((entry) => entry.type === "function" && entry.name === name);
    if (!item) throw new Error(`${extra.from} has no function ${name}`);
    return item;
  });
}

for (const { contract, name, file } of artifacts) {
  const events = extraEvents[contract] ? abiOf(extraEvents[contract]).filter((item) => item.type === "event") : [];
  const body = JSON.stringify([...abiOf(contract), ...viewsOf(contract), ...events], null, 2);
  writeFileSync(join(targetDir, `${file}.ts`), `${header}export const ${name} = ${body} as const;\n`);
}

const index = artifacts.map(({ name, file }) => `export { ${name} } from "./${file}";`).join("\n");
writeFileSync(join(targetDir, "index.ts"), `${header}${index}\n`);

console.log(`Exported ${artifacts.length} ABIs to ${targetDir}`);
