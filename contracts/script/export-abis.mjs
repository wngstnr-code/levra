import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const targetDir = join(root, "..", "packages", "shared", "abis");

const artifacts = [
  { contract: "IMarginRouter", name: "marginRouterAbi", file: "marginRouter" },
  { contract: "IRiskManager", name: "riskManagerAbi", file: "riskManager" },
  { contract: "ISessionOracle", name: "sessionOracleAbi", file: "sessionOracle" },
  { contract: "ILens", name: "lensAbi", file: "lens" },
  { contract: "IAnchoredStockOracle", name: "anchoredStockOracleAbi", file: "anchoredStockOracle" },
  { contract: "IMorpho", name: "morphoAbi", file: "morpho" },
];

const header = "// Generated by contracts/script/export-abis.mjs. Do not edit by hand.\n";

mkdirSync(targetDir, { recursive: true });

for (const { contract, name, file } of artifacts) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${contract}.sol`, `${contract}.json`), "utf8"));
  const body = JSON.stringify(artifact.abi, null, 2);
  writeFileSync(join(targetDir, `${file}.ts`), `${header}export const ${name} = ${body} as const;\n`);
}

const index = artifacts.map(({ name, file }) => `export { ${name} } from "./${file}";`).join("\n");
writeFileSync(join(targetDir, "index.ts"), `${header}${index}\n`);

console.log(`Exported ${artifacts.length} ABIs to ${targetDir}`);
